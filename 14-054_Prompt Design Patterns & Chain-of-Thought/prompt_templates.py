def build_book_classifier(review_text: str) -> str:
    """
    Constructs a few-shot prompt to classify a book review as POSITIVE,
    NEUTRAL, or NEGATIVE using XML delimiters.
    """
    prompt = f"""Classify the book review into one label: POSITIVE, NEUTRAL, or NEGATIVE.
Respond with only the single label.

<review>An unforgettable story with brilliant characters from start to finish.</review>
Sentiment: POSITIVE

<review>The book was decent for a weekend read, though parts of the middle dragged.</review>
Sentiment: NEUTRAL

<review>Poorly paced and predictable. I struggled to finish the first three chapters.</review>
Sentiment: NEGATIVE

<review>{review_text.strip()}</review>
Sentiment:"""
    return prompt


def build_refund_cot_prompt(request_details: str) -> str:
    """
    Constructs a Zero-shot Chain-of-Thought prompt to calculate a customer's
    refund amount based on store return policies.
    """
    prompt = f"""Calculate the customer's refund amount using these store policies:
- Books returned within 14 days of purchase receive a 100% refund.
- Books returned between 15 and 30 days after purchase receive a 50% refund.
- Books returned after 30 days are not eligible for a refund.

<request>
{request_details.strip()}
</request>

Let us think step by step. State which policy rule applies, show the calculation, and give the final refund amount."""
    return prompt


